# Приводим названия рубрик к единому виду для точного сравнения.
def normalize_label(value):
    # Убираем лишние пробелы, различия регистра и вариантов буквы ё.
    return " ".join(value.casefold().replace("ё", "е").split())


# Проверяем прямоугольник в порядке запад, юг, восток, север.
def validate_bbox(values):
    # Требуем ровно четыре числовые координаты.
    if len(values) != 4:
        # Поясняем ожидаемый порядок координат.
        raise ValueError("Нужны четыре координаты: запад юг восток север")
    # Преобразуем значения в числа.
    west, south, east, north = map(float, values)
    # Отбрасываем бесконечные числа и NaN.
    if not all(math.isfinite(v) for v in (west, south, east, north)):
        # Не допускаем некорректные координаты в запросе и фильтрации.
        raise ValueError("Координаты должны быть конечными числами")
    # Проверяем допустимые диапазоны и ненулевую площадь.
    if not (-180 <= west < east <= 180 and -90 <= south < north <= 90):
        # Для перехода через 180-й меридиан нужен отдельный прямоугольник.
        raise ValueError("Требуется: -180 <= запад < восток <= 180; -90 <= юг < север <= 90")
    # Возвращаем проверенные границы.
    return [west, south, east, north]


# Проверяем координаты одной организации, не подставляя центр области.
def valid_coordinates(value):
    # DOM передаёт координаты строкой, встроенный HTML — списком.
    if isinstance(value, str):
        # Разделяем строку долготы и широты.
        value = value.split(",")
    # При отсутствии ровно двух координат возвращаем неопределённое положение.
    if not isinstance(value, (list, tuple)) or len(value) != 2:
        # Нельзя включать такую организацию в область автоматически.
        return None
    # Логические значения не являются географическими координатами.
    if any(isinstance(part, bool) for part in value):
        # Сохраняем необходимость проверки положения.
        return None
    # Отдельно обрабатываем некорректные числовые значения.
    try:
        # Получаем долготу и широту.
        lon, lat = map(float, value)
    # Нечисловые поля означают отсутствие проверенных координат.
    except (ValueError, TypeError, OverflowError):
        # Сохраняем необходимость проверки положения.
        return None
    # Проверяем конечность значений и географические диапазоны.
    if not (math.isfinite(lon) and math.isfinite(lat) and -180 <= lon <= 180 and -90 <= lat <= 90):
        # Некорректное положение не используется при фильтрации.
        return None
    # Сохраняем порядок долгота, широта.
    return [lon, lat]


# Выбираем организации внутри области и проверяем заданные рубрики.
def classify_candidate(row, bbox, rubrics, boundary=None):
    # Нормализуем доступные координаты.
    position = valid_coordinates(row.get("coordinates_lon_lat"))
    # Неизвестные координаты обозначаем отдельной причиной исключения.
    if position is None:
        # Не выдаём непроверенное положение за попадание в область.
        return "missing_coordinates"
    # Распаковываем границы и координаты.
    west, south, east, north = bbox
    # Разделяем долготу и широту организации.
    lon, lat = position
    # Проверяем положение точки, включая границы прямоугольника.
    if not (west <= lon <= east and south <= lat <= north):
        # Отделяем результаты за пределами области.
        return "outside_bbox"
    # Проверяем точный контур после дешёвого прямоугольного отбора.
    if boundary is not None and not boundary.covers(position):
        # Исключаем отверстия и точки вне выбранного полигона.
        return "outside_polygon"
    # Для свободного запроса проверка рубрики не задаётся.
    if not rubrics:
        # В этом режиме принимается любая найденная организация внутри области.
        return "accepted"
    # Собираем фактические названия рубрик из карточки.
    actual = {normalize_label(name) for name in row.get("rubrics", [])}
    # При отсутствии рубрик не считаем категорию подтверждённой.
    if not actual:
        # Позволяем пользователю отдельно проверить такую запись.
        return "missing_rubrics"
    # Проверяем пересечение с разрешёнными рубриками.
    if not actual.intersection(normalize_label(name) for name in rubrics):
        # Поисковый запрос мог вернуть похожую, но другую категорию.
        return "rubric_mismatch"
    # Положение и рубрика соответствуют условиям.
    return "accepted"


# Читаем доступные поисковые категории из локального файла.
def load_categories():
    # Возвращаем готовые настройки, не обращаясь к справочному сервису.
    return json.loads(CATEGORY_FILE.read_text(encoding="utf-8"))["categories"]


# Преобразуем выбранные категории и свободные запросы в задания поиска.
def resolve_searches(categories, queries):
    # Настройки должны содержать списки строк, а не отдельную строку или null.
    if (
        # Настройки должны содержать списки строк, а не отдельную строку или null.
        not isinstance(categories, list)
        # Настройки должны содержать списки строк, а не отдельную строку или null.
        or not isinstance(queries, list)
        # Настройки должны содержать списки строк, а не отдельную строку или null.
        or any(not isinstance(item, str) for item in categories + queries)
    ):
        # Не разбираем ошибочный запрос по отдельным буквам.
        raise ValueError("categories и queries должны быть списками строк.")
    # Загружаем ограниченный список готовых категорий.
    catalog = load_categories()
    # Разрешаем выбирать категорию по ключу или отображаемому названию.
    aliases = {normalize_label(key): key for key in catalog}
    # Добавляем русские названия к допустимым обозначениям.
    # Сохраняем прежние короткие ключи при совпадении названия с опубликованной рубрикой.
    for key, item in catalog.items():
        # Первое соответствие не заменяется одинаковым названием из полного справочника.
        aliases.setdefault(normalize_label(item["label"]), key)
    # Подготавливаем очередь без повторов.
    selections = {}
    # Обрабатываем выбранные готовые категории.
    for value in categories:
        # Находим категорию по ключу или русскому названию.
        key = aliases.get(normalize_label(value))
        # Отклоняем неизвестные обозначения, чтобы не подменять их случайным поиском.
        if key is None:
            # Свободный запрос доступен как отдельный явный режим.
            raise ValueError(
                # Свободный запрос доступен как отдельный явный режим.
                f"Неизвестная категория: {value}. Используйте --list-categories или --query."
            )
        # Сохраняем запрос и требуемые рубрики.
        selections[key] = dict(catalog[key], key=key)
    # Обрабатываем пользовательские поисковые выражения.
    for query in queries:
        # Убираем лишние пробелы.
        query = query.strip()
        # Не допускаем пустые или чрезмерно длинные запросы.
        if not query or len(query) > 200:
            # Ограничение относится к длине текста, а не к объёму отзывов.
            raise ValueError("Свободный запрос должен содержать от 1 до 200 символов")
        # Помечаем свободный запрос отдельно от готовой категории.
        key = "query:" + normalize_label(query)
        # В свободном режиме не навязываем заранее заданные рубрики.
        selections[key] = {"key": key, "label": query, "query": query, "rubrics": []}
    # Требуем хотя бы одну категорию или поисковое выражение.
    if not selections:
        # Нельзя трактовать пустой ввод как все категории каталога.
        raise ValueError("Выберите хотя бы одну категорию или задайте --query")
    # Возвращаем задания в порядке выбора.
    return list(selections.values())


# Строим адрес обычной страницы поиска с выбранным участком карты.
def search_url(bbox, query):
    # Читаем границы области.
    west, south, east, north = bbox
    # Передаём центр, размер видимой области и текст поиска.
    params = {
        # Сохраняем центр выбранного участка карты.
        "ll": f"{(west + east) / 2},{(south + north) / 2}",
        # Сохраняем ширину и высоту видимого участка в градусах.
        "spn": f"{east - west},{north - south}",
        # Сохраняем поисковый запрос.
        "text": query,
        # Сохраняем русский язык интерфейса.
        "lang": "ru_RU",
    }
    # Это адрес пользовательской страницы, а не служебного метода получения данных.
    return "https://yandex.ru/maps/?" + urlencode(params)


# Извлекаем первые результаты из JSON, встроенного в HTML страницы поиска.
def extract_search_html(html):
    # Находим script со встроенным состоянием страницы.
    parser = StateScript()
    # Передаём HTML стандартному разборщику.
    parser.feed(html)
    # Читаем JSON из уже загруженной страницы.
    state = json.loads("".join(parser.parts))
    # Подготавливаем словарь организаций по идентификатору.
    rows = {}
    # Просматриваем панели страницы.
    for panel in state.get("stack", []):
        # Читаем организации из результатов поиска.
        for item in panel.get("results", {}).get("items", []):
            # Принимаем только организации, а не адреса и географические объекты.
            if item.get("type") != "business" or not str(item.get("id", "")).isdigit():
                # Здание без карточки организации сюда не относится.
                continue
