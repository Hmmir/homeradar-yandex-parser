"""Проверка границ GeoJSON и точное включение организаций в территорию."""

# Читаем координаты и приводим результат к обычным структурам JSON.
import json

# Проверяем числовые координаты без допусков к бесконечности.
import math

# Используем готовую геометрическую библиотеку для сложных контуров и отверстий.
from shapely import prepare

# Создаём точку организации и геометрию выбранной территории.
from shapely.geometry import Point, mapping, shape

# Объединяем несколько полигональных объектов без потери отверстий.
from shapely.ops import unary_union

# Объясняем ошибки самопересечения и другой некорректной топологии.
from shapely.validation import explain_validity


# Ограничиваем суммарное число вершин до создания геометрии GEOS.
MAX_BOUNDARY_VERTICES = 200_000


# Храним проверенную границу для многократной проверки координат организаций.
class Boundary:
    # Подготавливаем одну территорию перед обходом организаций.
    def __init__(self, geometry):
        # Сохраняем геометрию GEOS для точного пространственного отбора.
        self.shape = geometry
        # Создаём индекс один раз, без упрощения исходных координат.
        prepare(self.shape)
        # Приводим вложенные кортежи к спискам для совместимого кэша JSON.
        self.geojson = json.loads(json.dumps(mapping(geometry)))
        # Вычисляем прямоугольник поиска по фактическим координатам полигона.
        self.bbox = list(geometry.bounds)

    # Включаем границу контура; внутренняя часть отверстия исключается.
    def covers(self, position):
        # Проверяем долготу и широту без округления и проекции на центр области.
        return self.shape.covers(Point(position))


# Принимаем геометрию, Feature либо непустую коллекцию полигональных Feature.
def load_boundary(value):
    # Строим и индексируем только итоговую территорию, а не каждую часть коллекции.
    return Boundary(_read_geometry(value))


# Проверяем вложенные геометрии без лишней сериализации промежуточных частей.
def _read_geometry(value, vertices=None):
    # Ограничение относится ко всему файлу, включая все объекты коллекции.
    if vertices is None:
        # Передаём один счётчик во все вложенные геометрии.
        vertices = [0]
    # Разбираем только объекты GeoJSON.
    if not isinstance(value, dict):
        # Не допускаем подмену геометрии массивом или строкой.
        raise ValueError("Граница должна быть объектом GeoJSON.")
    # GeoJSON использует WGS84; другая заявленная система требует предварительного преобразования.
    if value.get("crs") is not None:
        # Не угадываем систему координат по числовым значениям.
        raise ValueError("Удалите crs после преобразования GeoJSON в WGS84: долгота, широта.")
    # Извлекаем отдельные полигональные геометрии без свойств и исполняемого содержимого.
    kind = value.get("type")
    # Коллекция позволяет загрузить несколько частей территории одним файлом.
    if kind == "FeatureCollection":
        # Проверяем форму коллекции до обращения к её элементам.
        features = value.get("features")
        # Пустой файл не обозначает выбранную область.
        if not isinstance(features, list) or not features:
            # Требуем хотя бы один полигональный объект.
            raise ValueError("FeatureCollection должна содержать полигональные объекты.")
        # Проверяем каждый Feature отдельно, включая его систему координат.
        parts = [_read_geometry(feature, vertices) for feature in features]
        # Объединяем соприкасающиеся и перекрывающиеся части вместо некорректного MultiPolygon.
        return unary_union(parts)
    # Свойства Feature не влияют на пространственный отбор.
    if kind == "Feature":
        # Проверяем вложенную геометрию по тем же правилам.
        return _read_geometry(value.get("geometry"), vertices)
    # Ограничиваем ввод площадными территориями.
    if kind not in {"Polygon", "MultiPolygon"}:
        # Точка или линия не заменяет площадь поиска.
        raise ValueError("Допустимы только Polygon и MultiPolygon.")
    # Получаем набор полигонов в едином формате.
    polygons = [value.get("coordinates")] if kind == "Polygon" else value.get("coordinates")
    # Проверяем наличие координат.
    if not isinstance(polygons, list) or not polygons:
        # Не передаём пустую геометрию библиотеке.
        raise ValueError("В границе отсутствуют координаты.")
    # Учитываем размер входа до построения пространственного индекса.
    # Проверяем внешний контур и отверстия каждого полигона.
    for polygon in polygons:
        # Каждый полигон должен иметь внешний контур.
        if not isinstance(polygon, list) or not polygon:
            # Не принимаем пустую часть MultiPolygon.
            raise ValueError("Полигон должен содержать хотя бы один контур.")
        # Проверяем все контуры без сокращения координат.
        for ring in polygon:
            # Замкнутый контур требует трёх вершин и повторённой начальной точки.
            if not isinstance(ring, list) or len(ring) < 4 or ring[0] != ring[-1]:
                # Не замыкаем чужой файл молча.
                raise ValueError(
                    # Не замыкаем чужой файл молча.
                    "Контур должен быть замкнут и содержать не менее четырёх координат."
                )
            # Подсчитываем вершины исходного файла.
            vertices[0] += len(ring)
            # Ограничиваем размер ручного импорта, а не точность геометрии.
            if vertices[0] > MAX_BOUNDARY_VERTICES:
                # Предлагаем разделить чрезмерно большой файл.
                raise ValueError("Во всей границе допускается до 200 000 вершин.")
            # Проверяем порядок и диапазоны каждой точки.
            for point in ring:
                # Поддерживаем только двумерные координаты WGS84.
                if not isinstance(point, list) or len(point) != 2:
                    # Высота и другие системы координат требуют отдельного преобразования.
                    raise ValueError("Координата должна содержать только долготу и широту.")
                # Исключаем строки, логические значения, NaN и бесконечность.
                if any(
                    # Исключаем строки, логические значения, NaN и бесконечность.
                    isinstance(number, bool)
                    # Исключаем строки, логические значения, NaN и бесконечность.
                    or not isinstance(number, (int, float))
                    # Исключаем строки, логические значения, NaN и бесконечность.
                    or abs(number) > 180
                    # Исключаем строки, логические значения, NaN и бесконечность.
                    or not math.isfinite(number)
                    # Исключаем строки, логические значения, NaN и бесконечность.
                    for number in point
                ):
                    # Сообщаем о неверном числовом вводе.
                    raise ValueError("Координаты должны быть конечными числами.")
                # Проверяем географические диапазоны.
                if not (-180 <= point[0] <= 180 and -90 <= point[1] <= 90):
                    # Не принимаем метрические координаты за градусы.
                    raise ValueError("Координаты выходят за диапазоны WGS84.")
            # Не трактуем переход через 180-й меридиан как большую плоскую территорию.
            if any(abs(a[0] - b[0]) > 180 for a, b in zip(ring, ring[1:])):
                # Для таких территорий требуется предварительное разделение.
                raise ValueError("Переход через 180-й меридиан не поддерживается.")
    # Строим полигон без исправления или упрощения чужой геометрии.
    geometry = shape(value)
    # Проверяем площадь и взаимное расположение контуров.
    if geometry.is_empty or not geometry.is_valid or geometry.area == 0:
        # Оставляем пользователю конкретную диагностическую причину.
        raise ValueError("Некорректная граница: " + explain_validity(geometry))
    # Передаём проверенную геометрию для подготовки единственного итогового индекса.
    return geometry
