# Показываем доступные города вместе с датой и источником каждой границы.
def list_cities():
    # Каталог локальный; функция не обращается к сервисам геокодирования.
    return json.loads((ROOT / "boundaries/catalog.json").read_text(encoding="utf-8"))["cities"]


# Читаем JSON конфигурации или границы с тем же ограничением размера, что у сценария.
def _read_json(path):
    # Поддерживаем строки и объекты Path.
    path = Path(path)
    # Отказываемся читать чрезмерно большой файл целиком.
    if path.stat().st_size > 10 * 1024 * 1024:
        # Предлагаем сократить территорию, сохранив её точную геометрию.
        raise ValueError("Файл территории больше 10 МБ; разделите его на части.")
    # Поддерживаем обычный UTF-8 и файлы с меткой BOM.
    return json.loads(path.read_text(encoding="utf-8-sig"))


# Объединяем выбор территории с категориями до запуска существующего сценария.
def _area_config(city, bbox, geometry, config, tags, queries):
    # Не выбираем молча между несколькими противоречивыми территориями.
    if sum(value is not None for value in (city, bbox, geometry, config)) != 1:
        # Требуем один из поддерживаемых способов ввода.
        raise ValueError("Укажите ровно один параметр: city, bbox, geometry или config.")
    # Сохраняем выбранный элемент каталога для диагностики возраста границы.
    city_info = None
    # Читаем конфиг, экспортированный картой, либо подготовленный словарь.
    if config is not None:
        # Копируем словарь, чтобы не изменять пользовательский объект.
        area = dict(config) if isinstance(config, dict) else _read_json(config)
    # Имя города разрешаем только по явному локальному каталогу.
    elif city is not None:
        # Проверяем тип до строковой нормализации.
        if not isinstance(city, str) or not city.strip():
            # Не принимаем пустое название и произвольные объекты.
            raise ValueError("city должен содержать название города из list_cities().")
        # Сопоставляем также идентификаторы и псевдонимы городов.
        matches = [
            # Сопоставляем также идентификаторы и псевдонимы городов.
            item
            # Сопоставляем также идентификаторы и псевдонимы городов.
            for item in list_cities()
            # Сопоставляем также идентификаторы и псевдонимы городов.
            if city.strip().casefold()
            # Сопоставляем также идентификаторы и псевдонимы городов.
            in {value.casefold() for value in [item["name"], item["id"], *item.get("aliases", [])]}
        ]
        # Не выбираем неизвестную или неоднозначную границу.
        if len(matches) != 1:
            # Для остальных территорий остаются прямоугольник и GeoJSON.
            raise ValueError(
                # Для остальных территорий остаются прямоугольник и GeoJSON.
                "Город не найден однозначно; используйте list_cities(), bbox или geometry."
            )
        # Сохраняем сведения о выбранной границе вместе с результатом.
        city_info = matches[0]
        # Подставляем точную локальную геометрию, не упрощая контур.
        area = {"geometry": _read_json(ROOT / city_info["file"])}
    # Прямоугольник принимает четыре координаты запад, юг, восток, север.
    elif bbox is not None:
        # Позволяем передать список или кортеж, например из обработчика карты.
        area = {"bbox": list(bbox)}
    # GeoJSON принимаем как словарь или путь к файлу.
    else:
        # Проверку геометрии выполняет существующий сценарий до открытия браузера.
        area = {"geometry": geometry if isinstance(geometry, dict) else _read_json(geometry)}
    # Файл конфига должен содержать объект, а не массив или число.
    if not isinstance(area, dict):
        # Возвращаем обычную ошибку Python вместо неясного сбоя дочернего процесса.
        raise ValueError("Конфиг должен содержать объект JSON.")
    # Явные категории и запросы заменяют соответствующие значения из конфига.
    for key, values in (("categories", tags), ("queries", queries)):
        # Значение None сохраняет выбор, сделанный на интерактивной карте.
        if values is not None:
            # Не превращаем одну строку в последовательность отдельных букв.
            if not isinstance(values, (list, tuple)) or any(
                # Не превращаем одну строку в последовательность отдельных букв.
                not isinstance(value, str)
                # Не превращаем одну строку в последовательность отдельных букв.
                for value in values
            ):
                # Требуем понятный формат списка поисковых настроек.
                raise ValueError(f"{key} должен быть списком строк.")
            # Формируем совместимый с существующим сценарием конфиг.
            area[key] = list(values)
    # Возвращаем входные параметры и источник границы независимо от сбора.
    return area, city_info


# Преобразуем сохранённые снимки в связанные таблицы без обращения к сети.
def load_results(output="review_results", *, max_reviews=None, with_reviews=True):
    # Разрешаем путь один раз, чтобы он не зависел от вложенных вызовов.
    folder = Path(output).resolve()
    # Не смешиваем полную выборку с файлом другого лимита.
    suffix = "" if max_reviews is None else f".limit{max_reviews}"
    # На время чтения защищаем всю папку от параллельного изменения.
    with output_lock(folder):
        # Читаем состав организаций именно из манифеста выбранного запуска.
        manifest = read_snapshot(folder / "organizations.json")
        # Не представляем отсутствующий манифест как успешный пустой поиск.
        if not manifest:
            # Указываем, какой файл нужен для загрузки результата.
            raise FileNotFoundError(f"Не найден корректный файл: {folder / 'organizations.json'}")
        # Создаём только необходимые две таблицы и словарь диагностики.
        organizations, reviews, runs = [], [], {}
        # Обрабатываем каждую найденную организацию один раз.
        for source in manifest["organizations"]:
            # Числовой идентификатор остаётся строкой для безопасного объединения таблиц.
            oid = str(source["organization_id"])
