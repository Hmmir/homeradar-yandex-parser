"""Безопасное сохранение снимков, проверка кэша и блокировка общей папки."""

# Разбираем и записываем обычные файлы JSON.
import json

# Синхронизируем данные и используем блокировки операционной системы.
import os

# Формируем уникальное имя резервной копии повреждённого файла.
import time

# Создаём временный файл рядом с итоговым снимком.
import tempfile

# Освобождаем блокировку при нормальном выходе и исключении.
from contextlib import contextmanager

# Приводим пути к единому абсолютному виду.
from pathlib import Path


# Записываем JSON атомарно, не изменяя прежний файл при ошибке сериализации.
def save_result(target, result):
    # Приводим путь к объекту файловой системы.
    target = Path(target)
    # Создаём папку для промежуточных и итоговых снимков.
    target.parent.mkdir(parents=True, exist_ok=True)
    # Храним только имя собственного временного файла.
    temporary = None
    # Любая ошибка должна оставить прежний снимок целым.
    try:
        # Выбираем уникальный файл на том же диске для атомарной замены.
        with tempfile.NamedTemporaryFile(
            # Выбираем уникальный файл на том же диске для атомарной замены.
            mode="w",
            # Читаем и записываем кириллицу в UTF-8.
            encoding="utf-8",
            # Выбираем уникальный файл на том же диске для атомарной замены.
            newline="\n",
            # Выбираем уникальный файл на том же диске для атомарной замены.
            dir=target.parent,
            # Выбираем уникальный файл на том же диске для атомарной замены.
            prefix=target.name + ".",
            # Выбираем уникальный файл на том же диске для атомарной замены.
            suffix=".tmp",
            # Выбираем уникальный файл на том же диске для атомарной замены.
            delete=False,
            # Выбираем уникальный файл на том же диске для атомарной замены.
        ) as stream:
            # Запоминаем путь для очистки при отказе записи.
            temporary = Path(stream.name)
            # Не допускаем нестандартных NaN и Infinity в сохранённом JSON.
            json.dump(result, stream, ensure_ascii=False, indent=2, allow_nan=False)
            # Перед заменой отправляем буфер Python файловой системе.
            stream.flush()
            # Синхронизируем содержимое собственного файла с диском.
            os.fsync(stream.fileno())
        # Заменяем итоговый файл только после полной успешной записи.
        temporary.replace(target)
    # Удаляем только свой временный файл при любом исходе.
    finally:
        # После успешной замены временный путь уже отсутствует.
        if temporary is not None:
            # Отказ замены сохраняет старый JSON и не оставляет неполную копию.
            temporary.unlink(missing_ok=True)


# Читаем кэш, сохраняя повреждённый оригинал для диагностики.
def read_snapshot(target, validator=None):
    # Принимаем строковый путь так же, как функция сохранения.
    target = Path(target)

    # Отклоняем нестандартные числовые константы вместо скрытого NaN в данных.
    def reject_constant(value):
        # Некорректный оригинал будет сохранён в резервной копии.
        raise ValueError(f"Недопустимая константа JSON: {value}")

    # Отсутствующий файл означает новый сбор.
    if not target.exists():
        # Новое задание не требует резервной копии.
        return {}
    # Отделяем повреждение содержимого от недоступности диска.
    try:
        # Принимаем также корректный UTF-8 с BOM из внешнего редактора.
        value = json.loads(target.read_text(encoding="utf-8-sig"), parse_constant=reject_constant)
        # Проверяем корневой объект и структуру конкретного вида снимка.
        if not isinstance(value, dict) or (validator is not None and not validator(value)):
            # Неверная структура не должна ломать возобновление.
            raise ValueError("Некорректная структура снимка")
        # Возвращаем совместимые записи без сокращения данных.
        return value
    # Ошибки доступа к файлу не маскируем как повреждение JSON.
    except (ValueError, UnicodeError) as error:
        # Формируем уникальную резервную копию рядом с исходным файлом.
        backup = target.with_name(target.stem + f".broken-{time.time_ns()}.json")
        # Сохраняем оригинал до начала повторного сбора.
        target.replace(backup)
        # Показываем, что файл восстановлен через новый сбор, а оригинал сохранён.
        print(
            # Показываем, что файл восстановлен через новый сбор, а оригинал сохранён.
            json.dumps(
                {
                    # Сохраняем поле event.
                    "event": "invalid_cache",
                    # Сохраняем путь поискового снимка внутри папки результатов.
                    "path": str(target),
                    # Сохраняем поле backup.
                    "backup": str(backup),
                    # Сохраняем поле reason.
                    "reason": str(error),
                },
                # Сохраняем русские названия в JSON без Unicode-последовательностей.
                ensure_ascii=False,
            ),
            # Сразу показываем состояние задачи в терминале.
            flush=True,
        )
        # Новый снимок будет создан обычным путём.
        return {}


# Не допускаем одновременные очереди, записывающие в одну папку.
@contextmanager
# Контекст освобождает системную блокировку даже при аварийном завершении процесса.
def output_lock(folder):
    # Используем одинаковый путь для относительных и абсолютных ссылок.
    folder = Path(folder).resolve()
    # Создаём только явно выбранную папку результатов.
    folder.mkdir(parents=True, exist_ok=True)
    # Файл остаётся на месте: его удаление могло бы создать гонку между процессами.
    with (folder / ".run.lock").open("a+b") as stream:
        # Блокировке Windows нужен хотя бы один существующий байт.
        if stream.seek(0, os.SEEK_END) == 0:
            # Содержимое не содержит персональных сведений или параметров запуска.
            stream.write(b"0")
            # Делаем байт доступным другим процессам до блокировки.
            stream.flush()
        # Все процессы блокируют один и тот же первый байт.
        stream.seek(0)
        # Выбираем системный механизм без дополнительной зависимости.
        if os.name == "nt":
            # Подключаем блокировку файла в Windows.
            import msvcrt

            # Подготавливаем неблокирующее получение замка.
            def acquire():
                # Выполняем системное действие над собственным файловым дескриптором.
                return msvcrt.locking(stream.fileno(), msvcrt.LK_NBLCK, 1)

            # Подготавливаем освобождение того же байта.
            def release():
                # Выполняем системное действие над собственным файловым дескриптором.
                return msvcrt.locking(stream.fileno(), msvcrt.LK_UNLCK, 1)

        # Другие поддерживаемые системы используют flock.
        else:
            # Подключаем системную блокировку Linux и macOS.
            import fcntl

            # Не ждём другую очередь бесконечно.
            def acquire():
                # Выполняем системное действие над собственным файловым дескриптором.
                return fcntl.flock(stream.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)

            # Освобождаем только собственный замок.
            def release():
                # Выполняем системное действие над собственным файловым дескриптором.
                return fcntl.flock(stream.fileno(), fcntl.LOCK_UN)

        # Отличаем занятую папку от успешного запуска.
        try:
            # Получаем исключительный доступ на время всей очереди.
            acquire()
        # Закрытие дескриптора не освобождает чужой замок.
        except OSError as error:
            # Предлагаем дождаться текущего запуска или выбрать другую папку.
            raise RuntimeError(f"Папка результатов занята другим запуском: {folder}") from error
        # Замок должен освобождаться при любом исходе пользовательского кода.
        try:
            # Выполняем поиск или сбор под одной блокировкой.
            yield
        # ОС также снимет замок при жёстком завершении процесса.
        finally:
            # Перед разблокировкой возвращаем позицию на первый байт.
            stream.seek(0)
            # Заканчиваем исключительное владение папкой.
            release()
